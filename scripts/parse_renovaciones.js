function parseData() {
    const lines = rawText.trim().split('\n');
    const records = [];
    const monthsMap = {
        'jul': 'Julio', 'ago': 'Agosto', 'sep': 'Septiembre',
        'oct': 'Octubre', 'nov': 'Noviembre', 'dic': 'Diciembre'
    };

    for (const l of lines) {
        const line = l.trim();
        if (!line) continue;
        
        // Match regex: (Poliza) (FinVig) (Mes) ($Monto)
        // Example: "M00-2-71-6762 01-jul-26 7 $25,469,024.69"
        const parts = line.split(/\s+/);
        if (parts.length >= 3) {
            const lastPart = parts[parts.length - 1];
            const mesPart = parts[parts.length - 2];
            const finVigPart = parts[parts.length - 3];
            const polizaPart = parts.slice(0, parts.length - 3).join(' ');

            let primaNeta = 0;
            if (lastPart.startsWith('$')) {
                const cleanNum = lastPart.replace(/[$,]/g, '');
                primaNeta = parseFloat(cleanNum) || 0;
            }

            const monthNum = parseInt(mesPart, 10);

            records.push({
                poliza: polizaPart,
                finVigencia: finVigPart,
                mesVigencia: monthNum,
                nombreMes: monthsMap[finVigPart.split('-')[1]] || 'Julio',
                primaNeta2025: primaNeta
            });
        }
    }

    const outputDir = path.join(__dirname, '..', 'data');
    if (!fs.existsSync(outputDir)) {
        fs.mkdirSync(outputDir, { recursive: true });
    }

    const outputFile = path.join(outputDir, 'renovaciones.json');
    fs.writeFileSync(outputFile, JSON.stringify(records, null, 2), 'utf8');
    console.log(`✅ Successfully generated data/renovaciones.json with ${records.length} policy records!`);
}

